  /**
 * Master inventory and progress tracker for Level 5 — "Mastery & Life Planning".
 *
 * This file is the single source of truth for what Level 5 contains, what each
 * chapter has to teach, which illustration and simulation it owns, which
 * official sources back its time-sensitive claims, and whether it has been
 * authored yet. `npm run check` cross-checks it against the syllabus and against
 * the chapters that actually exist, so the tracker cannot drift from reality:
 *
 *   - every syllabus chapter id must appear here (and nothing else may),
 *   - an entry marked `authored` must have a real chapter that renders the
 *     illustration and simulation it declares,
 *   - an illustration may be used at most three times across the whole level,
 *   - a simulation is a chapter's own; no two Level 5 chapters share one.
 *
 * Bands below map onto the six subject areas the level was specified with:
 *   "Investing & retirement"  -> retirement planning
 *   "Protection & life events" -> risk management and financial protection
 *   "Fraud & due diligence"   -> scams, fraud prevention and security
 *   "Spreadsheets & models"   -> personal finance spreadsheets and quantitative tools
 *   "AI tools"                -> AI tools for financial management
 *   "Capstone" + "Security & habits" -> building and maintaining a complete plan
 * The first band (money system) and "Institutions & contracts" carry the
 * syllabus's own early chapters, which come before those six areas begin.
 */

